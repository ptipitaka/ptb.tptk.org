def esc_attr(s: str) -> str:
    return s.replace("&", "&amp;").replace('"', "&quot;")


def patch_block(block: str, term: str | None, desc: str | None) -> str:
    lines = block.split("\n", 1)
    first = lines[0]
    rest = lines[1] if len(lines) > 1 else ""
    if term is not None:
        first = re.sub(r'term="[^"]*"', f'term="{esc_attr(term)}"', first, count=1)
    if desc is not None:
        first = re.sub(r'desc="[^"]*"', f'desc="{esc_attr(desc)}"', first, count=1)
    return first + ("\n" + rest if rest else "")


