def resolve_links(
    ruler: dict, bhikkhu: dict, term: str, link_ref: str | None
) -> list[dict]:
    if link_ref is None:
        if term not in MANUAL:
            raise SystemExit(f"Missing MANUAL for {term}")
        return [dict(x) for x in MANUAL[term]]
    if link_ref == "p1-sukkodana":
        return [dict(x) for x in MANUAL["เจ้าชายสุกโกทนศากยะ"]]
    if link_ref.startswith("r:"):
        k = link_ref[2:]
        return merge_links(ruler, k, None)
    if link_ref.startswith("b:"):
        k = link_ref[2:]
        return merge_links(bhikkhu, k, None)
    raise SystemExit(f"Bad link_ref {link_ref} for {term}")


