def sort_key(link: dict) -> tuple:
    import re

    h = link["href"]
    sk = link.get("_sort", 0)
    if "/part-1-" in h:
        return (0, sk, h)
    if "/part-2-" in h:
        return (1, sk, h)
    if "/part-3-" in h:
        return (2, sk, h)
    m = re.search(r"vol-(\d+)", h)
    vol = int(m.group(1)) if m else 999
    if "/part-4-" in h:
        return (3, vol, sk, h)
    return (4, vol, sk, h)


def merge_links(
    j: dict,
    key: str | None,
    extra: list[dict] | None = None,
) -> list[dict]:
    out: list[dict] = []
    seen: set[str] = set()
    if key and key in j:
        for Ld in j[key]:
            h = Ld["href"]
            if h in seen:
                continue
            seen.add(h)
            out.append(dict(Ld))
    if extra:
        for Ld in extra:
            h = Ld["href"]
            if h in seen:
                continue
            seen.add(h)
            out.append(dict(Ld))
    out.sort(key=sort_key)
    for o in out:
        o.pop("_sort", None)
    return out


