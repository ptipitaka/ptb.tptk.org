def resolve_links(j: dict, term: str, json_key: str | None) -> list[dict]:
    if term in MANUAL and json_key is None:
        return [dict(x) for x in MANUAL[term]]
    if term in MANUAL and json_key is not None:
        src = ALIASES.get(json_key, json_key)
        return merge_links(j, src, extra=MANUAL[term])
    if json_key is None:
        if term in MANUAL:
            return [dict(x) for x in MANUAL[term]]
        raise SystemExit(f"Missing links for {term}")
    src = ALIASES.get(json_key, json_key)
    extra = MANUAL.get(term)
    return merge_links(j, src, extra=extra)


def display_term(t: str) -> str:
    """คำอ้างอิง: พระ+ชื่อ -> พระภิกษุ ชื่อ (เช่นเดียวกับรูปแบบชื่อในหน้าพระภิกษุณี). ข้อยกเว้น: รายไม่ใช่ภิกษุ."""
    if t == "สุภัททปริพพาชก":
        return t
    if t.startswith("พระภิกษุ "):
        return t
    if t.startswith("พระ"):
        return "พระภิกษุ " + t.removeprefix("พระ")
    return t


def render_entry(links: list[dict], term: str, desc: str) -> str:
    term_out = display_term(term)
    lines = [
        f'<PtbWordIndexEntry term="{term_out}" desc="{desc}">',
        "",
    ]
    for L in links:
        tier = L.get("tier", "primary")
        lines.append("<PtbWordIndexRefs>")
        lines.append(
            f'  <PtbWordIndexLink href="{L["href"]}" label="{L["label"]}" tier="{tier}" />'
        )
        lines.append("</PtbWordIndexRefs>")
    lines.append("</PtbWordIndexEntry>")
    lines.append("")
    return "\n".join(lines)


