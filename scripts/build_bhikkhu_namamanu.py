def merge_links(
    j: dict,
    key: str | None,
    extra: list[dict] | None = None,
    omit_hrefs: set[str] | None = None,
) -> list[dict]:
    out: list[dict] = []
    seen: set[str] = set()
    if key and key in j:
        for L in j[key]:
            h = L["href"]
            if omit_hrefs and h in omit_hrefs:
                continue
            if h in seen:
                continue
            seen.add(h)
            out.append(dict(L))
    if extra:
        for L in extra:
            h = L["href"]
            if h in seen:
                continue
            seen.add(h)
            out.append(dict(L))
    out.sort(key=sort_key)
    return out


